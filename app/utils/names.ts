function titleWord(raw: string): string {
  const key = raw.toLowerCase()
  if (WORD_MAP[key]) return WORD_MAP[key]
  if (/^\d+$/.test(key)) return key
  // camel-ish tokens already joined: "arrowup" unlikely; handle dotted numbers like "2"
  return key.charAt(0).toUpperCase() + key.slice(1)
}

/** Human label: text.document → Text Document */
export function prettyLabel(name: string): string {
  return name
    .split(/[._]/)
    .filter(Boolean)
    .map(titleWord)
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/**
 * Grid label. Keeps variant words (Fill, Circle, ...) so tv / tv.fill /
 * tv.circle stay distinguishable in the grid.
 */
export function shortLabel(name: string): string {
  return prettyLabel(name)
}
